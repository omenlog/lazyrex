local M = {}

local generated_header = "-- Generated by lazyrex.nvim. Do not edit manually."
local generated_yaml_header = "# Generated by lazyrex.nvim. Do not edit manually."
local generated_shell_header = "# Generated by lazyrex.nvim. Do not edit manually."

local function rex_config_dir()
	local config_home = vim.env.XDG_CONFIG_HOME
	if not config_home or config_home == "" then
		config_home = vim.fn.expand("~/.config")
	end

	return config_home .. "/rex"
end

local function read_file(path)
	if vim.fn.filereadable(path) ~= 1 then
		return nil
	end
	return table.concat(vim.fn.readfile(path), "\n")
end

local function write_file(path, content)
	local result = vim.fn.writefile(vim.split(content, "\n", { plain = true }), path)
	if result ~= 0 then
		return "could not write " .. path
	end
end

local function write_owned_file(path, content)
	local existing = read_file(path)
	if existing == content then
		return false
	end
	if existing
			and not vim.startswith(existing, generated_header)
			and not vim.startswith(existing, generated_yaml_header)
			and not existing:find(generated_shell_header, 1, true)
	then
		return nil, path .. " already exists and is not managed by lazyrex.nvim"
	end

	local err = write_file(path, content)
	if err then
		return nil, err
	end
	return true
end

local function render_rex_config(config, lazygit_config_path)
	local bounds = table.concat(vim.tbl_map(tostring, config.bounds), ", ")
	local lines = {
		generated_header,
		"",
		'local terminal = "com.superlogical.terminal"',
		"local lazygit_config = " .. string.format("%q", lazygit_config_path),
		"",
		"local function lazygit_config_files()",
		'\tlocal result = rex.exec({ "lazygit", "--print-config-dir" }, { timeout = 2 })',
		"\tif result ~= nil and result.ok then",
		'\t\tlocal directory = result.stdout:match("^%s*(.-)%s*$")',
		'\t\tif directory ~= "" then return directory .. "/config.yml," .. lazygit_config end',
		"\tend",
		"\treturn lazygit_config",
		"end",
		"",
		"rex.action({",
		'\tname = "lazygit_open",',
		'\ttitle = "Open LazyGit",',
		'\tcategory = "Git",',
		'\tdescription = "Open LazyGit in a floating window for the current pane.",',
		'\targs = { nvim_server = "string?" },',
		"\trun = function(ctx, args)",
		'\t\tif ctx.block_id == nil then error("Open LazyGit from a Rex pane", 0) end',
		"",
		'\t\tlocal process, err = rex.block.call(terminal, "process", { block_id = ctx.block_id })',
		"\t\tif err ~= nil then error(err, 0) end",
		"\t\tlocal cwd = process.foreground and process.foreground.cwd",
		'\t\tif cwd == nil then error("Current pane has no readable working directory", 0) end',
		"",
		'\t\tlocal label = "lazygit:" .. (args.nvim_server or "default")',
		"\t\tlocal view, view_err = rex.session.view({})",
		"\t\tif view_err ~= nil then error(view_err, 0) end",
		"\t\tlocal origin_window_id",
		"\t\tfor _, window in ipairs(view.windows or {}) do",
		"\t\t\tfor _, layer in ipairs(window.layers or {}) do",
		"\t\t\t\tfor _, block in ipairs(layer.blocks or {}) do",
		"\t\t\t\t\tif block.block_id == ctx.block_id then origin_window_id = window.window_id end",
		"\t\t\t\t\tif layer.kind == \"floating\" and block.label == label then",
		'\t\t\t\t\t\tlocal status = rex.block.call(terminal, "process", { block_id = block.block_id })',
		"\t\t\t\t\t\tif status ~= nil and status.last_exit == nil then",
		"\t\t\t\t\t\t\tlocal restored, restore_err = rex.session.set_layer_state({",
		"\t\t\t\t\t\t\t\tlayer_id = layer.layer_id,",
		'\t\t\t\t\t\t\t\tstate = "normal",',
		"\t\t\t\t\t\t\t\tfocus = true,",
		"\t\t\t\t\t\t\t})",
		"\t\t\t\t\t\t\tif restore_err ~= nil then error(restore_err, 0) end",
		"\t\t\t\t\t\t\treturn restored",
		"\t\t\t\t\t\tend",
		"\t\t\t\t\tend",
		"\t\t\t\tend",
		"\t\t\tend",
		"\t\tend",
		"\t\tif origin_window_id == nil then error(\"Could not find the originating Rex window\", 0) end",
		"",
		"\t\tlocal command = { \"env\", \"LG_CONFIG_FILE=\" .. lazygit_config_files() }",
		"\t\tif args.nvim_server ~= nil then table.insert(command, \"NVIM=\" .. args.nvim_server) end",
		'\t\ttable.insert(command, "lazygit")',
		"",
		"\t\tlocal layer, layer_err = rex.session.new_layer({",
		"\t\t\twindow_id = origin_window_id,",
		"\t\t\tbounds = { " .. bounds .. " },",
		"\t\t\tfocus = true,",
		"\t\t\tlayout = rex.layout.block({",
		'\t\t\t\tflavor = "com.superlogical.terminal.shell",',
		"\t\t\t\tlabel = label,",
		"\t\t\t\toptions = { command = command, cwd = cwd },",
		"\t\t\t}),",
		"\t\t})",
		"\t\tif layer_err ~= nil then error(layer_err, 0) end",
		"\t\treturn layer",
		"\tend,",
		"})",
	}

	return table.concat(lines, "\n")
end

local function render_lazygit_config(helper_path)
	return table.concat({
		generated_yaml_header,
		"os:",
		"  edit: " .. string.format("%q", helper_path .. ' "{{filename}}"'),
		"  editAtLine: " .. string.format("%q", helper_path .. ' "{{filename}}" {{line}}'),
		"  editInTerminal: false",
	}, "\n")
end

local function render_helper()
	return [[#!/bin/sh
# Generated by lazyrex.nvim. Do not edit manually.
set -eu

file=$1
line=${2:-}

nvim --server "$NVIM" --remote-tab "$file"
if [ -n "$line" ]; then
  nvim --server "$NVIM" --remote-send ":${line}<CR>"
fi

layer_id=$(rex session inspect "$REX_SESSION" --json | jq -r --arg block "$REX_BLOCK" '
  .windows[] | .layers[]
  | select(.kind == "floating")
  | select(any(.blocks[]?; .block_id == $block))
  | .layer_id
' | head -n 1)

if [ -n "$layer_id" ]; then
  rex api call -s "$REX_SESSION" session.set_layer_state \
    "{\"layer_id\":\"$layer_id\",\"state\":\"minimized\"}" >/dev/null
fi
]]
end

local function ensure_loader(init_path)
	local init = read_file(init_path) or ""
	if init:find('require("lazyrex")', 1, true) or init:find("require('lazyrex')", 1, true) then
		return false
	end

	local loader = "-- Load lazyrex.nvim's generated Rex integration.\nrequire(\"lazyrex\")"
	local legacy_loader = "-- Load lazygit.nvim's generated Rex integration.\nrequire(\"lazygit\")"
	local legacy_start = init:find(legacy_loader, 1, true)
	if legacy_start then
		local updated = init:sub(1, legacy_start - 1) .. loader .. init:sub(legacy_start + #legacy_loader)
		local err = write_file(init_path, updated)
		if err then
			return nil, err
		end
		return true
	end

	local err = write_file(init_path, init == "" and loader or init .. "\n\n" .. loader)
	if err then
		return nil, err
	end
	return true
end

---@param config table
---@return string|nil err
function M.sync(config)
	local directory = rex_config_dir()
	local integration_dir = directory .. "/lazyrex"
	vim.fn.mkdir(integration_dir, "p")

	local integration_init_path = integration_dir .. "/init.lua"
	local lazygit_config_path = integration_dir .. "/lazygit.yml"
	local helper_path = integration_dir .. "/lazygit-edit"
	for _, file in ipairs({
		{ path = integration_init_path, content = render_rex_config(config, lazygit_config_path) },
		{ path = lazygit_config_path, content = render_lazygit_config(helper_path) },
		{ path = helper_path,         content = render_helper() },
	}) do
		local _, err = write_owned_file(file.path, file.content)
		if err then
			return err
		end
	end

	if vim.fn.setfperm(helper_path, "rwxr-xr-x") == 0 then
		return "could not make " .. helper_path .. " executable"
	end

	local _, loader_err = ensure_loader(directory .. "/init.lua")
	if loader_err then
		return loader_err
	end
	if vim.fn.executable(config.rex_path) == 1 then
		local result = vim.system({ config.rex_path, "config", "reload" }, { text = true }):wait()
		if result.code ~= 0 then
			return "could not reload Rex: " .. result.stderr
		end
	end
end

return M
